def _patterns(raw: Sequence[str]) -> list[str]:
    """The comma-separated *raw* values as one list of lower-cased patterns."""
    return [p.strip().casefold() for value in raw for p in value.split(",") if p.strip()]


def _selected(key: str, schema: SchemaConfig, patterns: Sequence[str]) -> bool:
    """Whether table *key* matches one of *patterns* by its key or by ``schema.name``."""
    if not patterns:
        return True
    definition = schema.tables[key]
    qualifier = ".".join(effective_qualifier(key, definition.db_schema))
    name = split_table_key(key).name
    names = {key.casefold(), (f"{qualifier}.{name}" if qualifier else name).casefold()}
    return any(fnmatch.fnmatchcase(n, p) for n in names for p in patterns)


def _write_atomically(path: Path, text: str, bom: bool) -> bool:
    """Write *text* to *path* (a temporary file, then a rename); ``False`` after saying why when it fails."""
    temporary = path.with_name(path.name + ".tmp")
    try:
        temporary.write_bytes((b"\xef\xbb\xbf" if bom else b"") + text.encode("utf-8"))
        os.replace(temporary, path)
    except OSError as exc:
        print(f"\ncannot write {path}: {_describe(exc)}", file=sys.stderr)
        return False
    return True


def _connect(args: argparse.Namespace) -> Generate | None:
    """The wizard's model as a ``prompt -> JSON`` function; ``None`` after saying why when it cannot be used.

    Resolved, vetted and announced by :func:`setup_project.setup_wizard_llm`:
    a remote endpoint is refused unless ``LLM_ALLOW_REMOTE=true``. A model that does not
    answer, and the mock provider, draft nothing, so they are errors here.
    """
    import setup_project as wizard

    try:
        llm = wizard.setup_wizard_llm(
            args,
            mock_fallback=False,
            sends=(
                "Table and column names, types and relationships (and, with --samples, label values)"
            ),
        )
    except (ValueError, wizard.RemoteLLMNotAllowedError, wizard.WizardLLMUnavailableError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return None
    if llm.provider == "mock":
        print(
            "ERROR: the mock provider answers nothing, so no description would be drafted. "
            "Point WIZARD_LLM_BASE_URL (or OPENAI_BASE_URL) at a model.",
            file=sys.stderr,
        )
        return None
    return lambda prompt: llm.generate(prompt, expect_json=True)


def _collect_samples(
    facts_columns: Sequence[tuple[str, str]],
    table: str,
    source: str,
    qualifier: str,
    fetch: SampleFetcher,
) -> dict[str, tuple[str, ...]]:
    """The label values of one table, read through *fetch* (:func:`~schema_data.describe_prompt.label_samples`).

    A failure to read a column gives none for it. A table whose schema has several parts
    (a table in another database of the same server) is not sampled.
    """
    if "." in qualifier:
        return {}

    def read(column: str) -> Sequence[str]:
        try:
            return fetch(source, qualifier, table, column)
        except Exception:  # noqa: BLE001 - a column that cannot be read gives no samples
            return []

    return label_samples(table, facts_columns, read)


def _ask(generate: Generate, facts: TableFacts, language: str, ceiling: int) -> TableAnswer:
    """Ask the model about one table; return the usable part of its answer.

    ``max_tokens`` is sized for the number of columns asked about
    (:func:`~schema_data.describe_prompt.max_tokens_for`) for this call only.

    Raises
    ------
    ValueError
        When the answer is not JSON, not an object, or holds nothing usable.
    Exception
        Whatever the transport raises (timeout, HTTP error).
    """
    wanted = len(facts.wanted_columns) + int(facts.describe_table)
    tokens = max_tokens_for(wanted, cfg.settings.llm_num_predict, ceiling)
    # One process, one request at a time: the setting is read when the request is built.
    with cfg.override_settings(llm_num_predict=tokens):
        answer = generate(build_prompt(facts, language))
    return parse_answer(answer, facts)


def _summary(run: _Run, selected: int, output: Path, wrote: bool) -> list[str]:
    drafted_tables = sum(1 for d in run.drafts.values() if d.drafted)
    descriptions = sum(d.description != "" for d in run.drafts.values())
    columns = sum(len(d.columns) for d in run.drafts.values())
    out = [
        "== summary ==",
        f"  tables selected: {selected}",
        f"  drafted: {descriptions} table description(s) and {columns} column description(s) in {drafted_tables} table(s)",
    ]
    if run.carried:
        out.append(f"  kept from the earlier output (--resume): {run.carried} table(s)")
    if run.left_over:
        out.append(
            f"  columns the model left undescribed: {run.left_over} (they keep the description they had)"
        )
    if run.ignored:
        out.append(f"  entries of the answers that were ignored (unknown names, curated columns, empty texts): {run.ignored}")
    out.append(f"  failed tables: {len(run.failed)}")
    out.extend(f"    {key}: {why}" for key, why in run.failed[:_MAX_LISTED])
    if len(run.failed) > _MAX_LISTED:
        out.append(f"    ... and {len(run.failed) - _MAX_LISTED} more")
    if run.failed or run.interrupted:
        out.append(f"  run again with --resume to ask about the {'failed ' if run.failed else 'remaining '}tables")
    if wrote:
        out.append(f"written: {output}")
        out.append(
            "  every drafted line ends with # REVIEW and the file starts with a draft header: read it, "
            "correct it, replace schema.yaml with it, then delete the header line"
        )
    return out


def main(
    argv: Sequence[str] | None = None,
    *,
    generate: Generate | None = None,
    fetch_samples: SampleFetcher | None = None,
) -> int:
    """Run the script; returns the process exit code.

    Parameters
    ----------
    argv:
        Command-line arguments; ``sys.argv[1:]`` when ``None``.
    generate:
        The model, ``prompt -> parsed JSON``. Defaults to the wizard's model
        (:func:`setup_project.setup_wizard_llm`); tests inject a fake.
    fetch_samples:
        Reads the values of one column for ``--samples``. Defaults to
        :func:`default_sample_fetcher`; tests inject a fake. Never called
        without ``--samples``.

    Returns
    -------
    int
        ``EXIT_OK``, ``EXIT_FAILED_TABLES`` or ``EXIT_ERROR`` (see the module docstring).
    """
    args = _build_parser().parse_args(argv)
    schema_path = args.schema or schema_yaml_path()
    output = args.output or schema_path.with_name(OUTPUT_FILENAME)
    if args.max_tokens < 1:
        print("ERROR: --max-tokens must be a positive number", file=sys.stderr)
        return EXIT_ERROR

    print(f"schema: {schema_path}")
    try:
        raw = schema_path.read_bytes()
    except OSError as exc:
        print(f"cannot read {schema_path}: {_describe(exc)}", file=sys.stderr)
        return EXIT_ERROR
    has_bom = raw.startswith(b"\xef\xbb\xbf")
    try:
        original = raw.decode("utf-8-sig")
        schema = validate_schema_yaml_text(original)
        targets = find_targets(original)
    except (UnicodeDecodeError, ValueError) as exc:
        print(f"cannot use {schema_path}: {_describe(exc)}", file=sys.stderr)
        return EXIT_ERROR

    patterns = _patterns(args.tables)
    chosen = [t for t in targets if _selected(t.key, schema, patterns)]
    print(
        f"{len(schema.tables)} table(s); {len(targets)} with descriptions to draft "
        f"({sum(t.wanted for t in targets)} descriptions)"
        + (f"; {len(chosen)} match --tables" if patterns else "")
    )
    if not chosen:
        print(
            "nothing to describe: no table matches --tables" if targets
            else "nothing to describe: every table and column description is already written"
        )
        return EXIT_OK

    writing = not args.dry_run
    if writing and output.resolve() == schema_path.resolve():
        print(f"refusing to overwrite {schema_path}; choose another --output", file=sys.stderr)
        return EXIT_ERROR

    # Prove the line editor can write every description before the model is asked anything.
    try:
        probe = [
            TableDraft(t.key, "x" if t.describe_table else "", {c: "x" for c in t.columns}) for t in chosen
        ]
        verify_described(schema, validate_schema_yaml_text(render_described_text(original, schema, probe)), probe)
    except ValueError as exc:  # LayoutError is a ValueError
        print(f"cannot edit {schema_path}: {_describe(exc)}", file=sys.stderr)
        return EXIT_ERROR

    run = _Run()
    previous_exists = output.exists()
    if previous_exists and writing and not (args.resume or args.force):
        print(
            f"{output} exists: --resume continues it (and keeps what it holds), --force replaces it; "
            "not touching it",
            file=sys.stderr,
        )
        return EXIT_ERROR
    if args.resume and previous_exists:
        try:
            earlier = output.read_bytes().decode("utf-8-sig")
            kept = carried_drafts(original, earlier)
        except (OSError, UnicodeDecodeError, ValueError) as exc:
            print(f"cannot use {output} to resume: {_describe(exc)}", file=sys.stderr)
            return EXIT_ERROR
        # Every table drafted before is kept, also one outside this run's --tables: a
        # second run over other tables must not drop the first run's work.
        run.drafts = dict(kept)
        run.carried = len(run.drafts)
    elif args.resume:
        print(f"--resume: {output} does not exist yet, starting from the beginning")
    pending = [t for t in chosen if t.key not in run.drafts]
    print(
        f"asking about {len(pending)} table(s)"
        + (f"; {run.carried} already drafted in {output.name}" if run.carried else "")
    )

    if args.dry_run:
        for target in pending:
            print(f"  {target.key}: {int(target.describe_table)} table + {len(target.columns)} column description(s)")
        print("\ndry run: no model was asked and nothing was written")
        return EXIT_OK

    if pending:
        generate = generate or _connect(args)
        if generate is None:
            return EXIT_ERROR
        if args.samples:
            print(
                "  --samples: a few label values (never personal or contact columns; no dates, numbers, "
                "codes, phones, addresses) are read and shown to the model."
            )
            fetch_samples = fetch_samples or default_sample_fetcher()
        _draft_all(
            pending, schema, original, schema_path, generate, args, run,
            fetch_samples if args.samples else None,
            lambda: _save(output, original, schema, run, has_bom),
        )

    wrote = bool(run.drafts) and _save(output, original, schema, run, has_bom)
    if run.drafts and not wrote:
        return EXIT_ERROR
    print()
    print("\n".join(_summary(run, len(chosen), output, wrote)))
    return EXIT_FAILED_TABLES if (run.failed or run.interrupted) else EXIT_OK


def _save(output: Path, original: str, schema: SchemaConfig, run: _Run, has_bom: bool) -> bool:
    """Render the drafts so far, prove the result, and write it. ``False`` after saying why when it cannot."""
    order = {key: n for n, key in enumerate(schema.tables)}
    drafts = sorted((d for d in run.drafts.values() if d.drafted), key=lambda d: order[d.key])
    if not drafts:
        return True
    try:
        text = render_described_text(original, schema, drafts)
        verify_described(schema, validate_schema_yaml_text(text), drafts)
    except ValueError as exc:
        print(f"\nnot written: {_describe(exc)}", file=sys.stderr)
        return False
    return _write_atomically(output, text, has_bom)


def _draft_all(
    pending: Sequence[TableTarget],
    schema: SchemaConfig,
    original: str,
    schema_path: Path,
    generate: Generate,
    args: argparse.Namespace,
    run: _Run,
    fetch_samples: SampleFetcher | None,
    checkpoint: Callable[[], bool],
) -> None:
    """Ask about each table in *pending*, recording drafts and failures in *run*.

    A table that fails is recorded and the loop goes on. The output is written
    through *checkpoint* after every table that gave something. Ctrl-C stops the
    loop and sets ``run.interrupted``.
    """
    directory = schema_path.parent
    listed = read_listed_relationships(directory)
    aliases = entity_aliases(directory)
    try:
        default_source = _default_source() if fetch_samples is not None else ""
        for position, target in enumerate(pending, 1):
            key = target.key
            definition = schema.tables[key]
            print(f"  [{position}/{len(pending)}] {key} ...", end=" ", flush=True)
            try:
                samples: Mapping[str, Sequence[str]] | None = None
                if fetch_samples is not None:
                    qualifier = ".".join(effective_qualifier(key, definition.db_schema))
                    source = (definition.datasource or (default_source,))[0]
                    samples = _collect_samples(
                        [(name, definition.column_types.get(name, "")) for name in target.columns],
                        split_table_key(key).name, source, qualifier, fetch_samples,
                    )
                facts = table_facts(
                    key, definition, target,
                    relationships=relationship_notes(key, definition, schema, listed),
                    aliases=aliases.get(key, ()),
                    samples=samples,
                )
                answer = _ask(generate, facts, args.language, args.max_tokens)
            except Exception as exc:  # noqa: BLE001 - one table failing must not stop the run
                why = _describe(exc)
                run.failed.append((key, why))
                print(f"FAILED ({why})")
                continue
            run.drafts[key] = TableDraft(key, answer.description, answer.columns)
            missing = len(facts.wanted_columns) - len(answer.columns)
            run.left_over += missing
            run.ignored += answer.ignored
            print(
                f"{int(bool(answer.description))} table + {len(answer.columns)} column description(s)"
                + (f", {missing} column(s) left undescribed" if missing else "")
            )
            checkpoint()
    except KeyboardInterrupt:
        run.interrupted = True
        print("\ninterrupted")


def _default_source() -> str:
    """The name of the default data source (``default`` without a ``datasources.yaml``)."""
    from database.datasources import default_datasource_name

    return default_datasource_name()


