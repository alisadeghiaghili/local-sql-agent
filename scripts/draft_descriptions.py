Generate = Callable[[str], object]

#: ``fetch(source, schema, table, column) -> distinct values`` for ``--samples``.
SampleFetcher = Callable[[str, str, str, str], Sequence[str]]

#: How many failed tables the summary lists before ``... and N more``.
_MAX_LISTED = 40


def default_sample_fetcher() -> SampleFetcher:
    """The reader ``--samples`` uses: up to 51 distinct values of one column.

    It opens the engine the application itself uses for the table's data source
    (:func:`database.connection.get_engine`) and runs the wizard's own query
    (``SELECT DISTINCT`` of one column, ``NOT NULL``, ordered, at most 51 rows;
    a failure gives no values).

    Returns
    -------
    SampleFetcher
    """

    def fetch(source: str, schema: str, table: str, column: str) -> Sequence[str]:
        from core.value_shapes import MAX_DISTINCT_VALUES
        from database.connection import get_engine
        from database.schema_inspector import _fetch_samples

        return _fetch_samples(get_engine(source), schema or None, table, column, MAX_DISTINCT_VALUES + 1)

    return fetch


@dataclass
class _Run:
    """What one run has done, for the summary."""

    drafts: dict[str, TableDraft] = field(default_factory=dict)
    carried: int = 0
    failed: list[tuple[str, str]] = field(default_factory=list)
    left_over: int = 0
    ignored: int = 0
    interrupted: bool = False


def _describe(exc: BaseException) -> str:
    """One short line about *exc*, without credentials or quoted values."""
    first = (str(exc).strip().splitlines() or [""])[0]
    return f"{type(exc).__name__}: {redact_error_text(first)[:160]}"


