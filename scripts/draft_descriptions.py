"""Draft the descriptions ``schema.yaml`` lacks, with the setup wizard's model, for review.

Usage (from the repo root, with the server's environment active)::

    python scripts/draft_descriptions.py                         # write schema.described.yaml
    python scripts/draft_descriptions.py --dry-run               # list what would be asked; no model, no file
    python scripts/draft_descriptions.py --tables 'sales.*'      # only these tables
    python scripts/draft_descriptions.py --language en           # English instead of Persian
    python scripts/draft_descriptions.py --resume                # continue an interrupted run
    python scripts/draft_descriptions.py --samples               # also show label values (see below)

Why it exists
-------------
On a first install nobody has curated ``schema.yaml``. The inspector and
``scripts/sync_schema.py --add-tables`` describe a table by its own name
(``Sales_Fact.Trade``) and a column by its type (``bigint column``), and the
preflight (``python -m scripts.verify_deployment``, the check ``project_config/
is curated, not a raw draft``) refuses a file that is mostly that: a
description that only repeats the name starves table retrieval, which matches
the words of a question against the words of the descriptions. This script
asks the model that the setup wizard asks for one table at a time and writes
what it answers where those descriptions are, for a person to read. It is the
same pattern as ``sync_schema.py``: it proposes a file next to ``schema.yaml``
and never overwrites ``schema.yaml``.

What it does
------------
* Reads ``schema.yaml`` (``--schema PATH``, default the one of
  ``PROJECT_CONFIG_DIR``) and finds every table description that is empty, the
  inspector's placeholder or only the table's name, and every column
  description that is empty or only ``<type> column``. These are the tests of
  the preflight (:mod:`core.config_doctor`), so what this script drafts is
  exactly what the preflight objects to. A description a person wrote is never
  a target and is never changed.
* Asks the model once per table (:func:`llm.wizard_llm.WizardLLM.generate`):
  the table's key, schema and data source, its column names and types, the
  notes already written, the relationships that name the table (``schema.yaml``,
  ``relationships.yaml``, the declared ones of ``relationships.proposed.yaml``)
  and its aliases in ``entities.yaml``. Names, types and keys only: **no row
  value is read or sent** unless ``--samples`` is given.
* Writes ``schema.described.yaml`` next to the input (``--output``): the input
  text with the drafted descriptions put in line by line. Every other line,
  comment, key, flag and the order of everything stay as they were, and the
  script proves it by parsing its own output and comparing it with the input
  plus exactly the drafted descriptions (:mod:`schema_data.describe`).
  Each drafted line ends with ``# REVIEW``.
* Starts the file with a draft header,
  ``# AUTO-GENERATED by draft_descriptions.py``. While it is there the
  preflight check ``project_config/ is curated, not a raw draft`` FAILs on the
  file. Read the descriptions, correct them, replace ``schema.yaml`` with the
  file, delete the header line, and the check passes.

The model
---------
The endpoint is the wizard's (:func:`setup_project.setup_wizard_llm`): the flags
``--llm-provider``, ``--llm-model`` and ``--llm-base-url``, then
``WIZARD_LLM_PROVIDER`` / ``WIZARD_LLM_MODEL`` / ``WIZARD_LLM_BASE_URL``, then
the application's ``OPENAI_BASE_URL`` / ``OPENAI_MODEL`` / ``OPENAI_API_KEY``.
It prints one line naming the model and endpoint (never the key). An endpoint
that is not local is refused unless ``LLM_ALLOW_REMOTE=true``, exactly as the
application and the wizard refuse it. Unlike the wizard it does not fall back to
a mock model when the endpoint does not answer: a mock drafts nothing, so
the run stops with an error.

Each call is sized for its table: ``max_tokens`` is about 60 tokens per
column asked about plus a fixed part, never less than ``LLM_NUM_PREDICT`` and
never more than ``--max-tokens`` (default 8192). A model that reasons before it
answers needs the room; a table of several hundred columns does not fit in
one answer and is reported as failed.

Language
--------
``--language fa`` (the default) writes Persian, the language of the
questions; ``--language en`` writes English. A table is described in one
sentence (what one row is), a column in a few words. The model is told to
describe only what the names, types, keys and relationships show, not to invent
business facts, and to end a guess with ``(?)``.

``--samples``
-------------
Off by default. With it, a few distinct values of the label columns (a column
named name, title, kind, status, type, category, class, label, caption or group,
of at most 50 distinct values) are read from the database and shown to the model
beside the column, so a lookup table's statuses can be described by what they
hold. The rules are the wizard's (:mod:`core.value_shapes`): a column named like
personal or contact data is never read; a date, number or code, phone number,
e-mail or IP address, URL, address, masked value, error text or value over 40
characters is never shown; at most 5 values per column and 20 per table. Those
values are sent to the endpoint like the names are. It needs the database
logins of ``datasources.yaml`` / ``.env``; nothing is written to a database.

Robustness
----------
* A table the model fails on (an unparsable or empty answer, a timeout) is
  recorded and the run goes on. The summary lists them; run again with
  ``--resume``.
* ``--resume`` continues an interrupted or partly failed run: the tables
  already drafted in the existing output are kept (as they are in the file
  now, so a correction made by hand survives) and the model is asked only
  about the others. Without ``--resume`` the script refuses to replace an
  existing output, so a reviewed draft is not lost to a second run; ``--force``
  starts over.
* The output is written after every table, so an interrupted run loses at most
  the table in progress.
* ``--tables 'Schema.*'`` (repeatable, comma-separated, case-insensitive)
  limits the run to the tables whose key, or ``schema.name``, matches.
* Names in the answer that the table does not have are ignored; a column the
  model leaves out keeps the description it had; nothing is ever removed.

Exit codes
----------
0 -- done (or nothing to describe); 1 -- the run ended but some tables failed
or it was interrupted (the output holds the rest); 2 -- nothing could be
decided or written: ``schema.yaml`` is invalid or laid out in a way the line
editor cannot edit, the model was refused or does not answer, the output
exists and neither ``--resume`` nor ``--force`` was given, or the output could
not be written.
"""

