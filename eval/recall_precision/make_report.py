"""Render recall_precision_report.md from the most recent run's JSON.

Run from the repo root::

    PYTHONIOENCODING=utf-8 py eval/recall_precision/make_report.py

It reads ``recall_precision_run.json`` (produced by
``evaluate_recall_precision.py``) and writes ``recall_precision_report.md``
so the report is regenerated reproducibly after every (re)run.
"""
from __future__ import annotations

import collections
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
RUN = HERE / "recall_precision_run.json"
OUT = HERE / "recall_precision_report.md"
CSV = HERE / "recall_precision_results.csv"


def pct(x):
    return "n/a" if x is None else f"{x * 100:.1f}%"


def cell(s):
    return str(s).replace("|", "/").replace("\n", " ") if s is not None else ""


def main():
    d = json.load(open(RUN, encoding="utf-8"))
    rows, S = d["rows"], d["summary"]
    B, A = S["B"], S["A"]

    miss_b = collections.Counter()
    extra_b = collections.Counter()
    miss_a = collections.Counter()
    for r in rows:
        for m in r["B_missing"].split(" | "):
            if m.strip() and r["B_missing"] != "-":
                miss_b[m.strip()] += 1
        for m in r["B_extra"].split(" | "):
            if m.strip() and r["B_extra"] != "-":
                extra_b[m.strip()] += 1
        for m in r["A_missing"].split(" | "):
            if m.strip() and r["A_missing"] != "-":
                miss_a[m.strip()] += 1

    mis = [r for r in rows if r.get("B_misroute") == "yes"]
    mis_by_cat = collections.Counter(r["category"] for r in mis)

    scored = [r for r in rows if isinstance(r.get("B_recall_raw"), (int, float))]
    best = sorted(scored, key=lambda x: (-x["B_recall_raw"], -x["B_precision_raw"]))[:8]
    worst = sorted(scored, key=lambda x: (x["B_recall_raw"], x["B_precision_raw"]))[:12]

    corrs = [int(r["B_corrections"]) for r in rows if str(r.get("B_corrections", "")).isdigit()]

    L = []
    w = L.append
    w("# Recall / Precision Evaluation — NLQ Interpretation Pipeline")
    w("")
    w("_Benchmark over the IME auction warehouse NLQ system. Generated by "
      "`make_report.py` from the most recent run — re-run it after any "
      "re-execution to refresh every number below._")
    w("")
    w("## 1. Scope and method")
    w("")
    w("The benchmark measures how faithfully the system **interprets** a Persian")
    w("business question — i.e. which requirement items it extracts — rather than")
    w("whether the final SQL string matches a reference. Two layers are scored:")
    w("")
    w("| Layer | What it is | Needs model? | Role |")
    w("|---|---|---|---|")
    w("| **B** | Full production pipeline: real model (Qwen3.8-27B-FP8) + live warehouse; the generated T-SQL is parsed back into a requirement set. | yes | **Headline** — end-to-end interpretation |")
    w("| **A** | Deterministic pre-LLM retrieval only: the ring filter and Persian-calendar date facets that `ValueRetriever`/dimension matching resolve before any model call. | no | Diagnostic of the value-extraction component |")
    w("")
    w("A **requirement** is one typed fact the question demands: `metric`, `entity`,")
    w("`filter`, `date`, `grouping`, `ordering`, `top`, or `exclusion`. Scoring is")
    w("semantic, not string-equality: ring names match by stored value, relative")
    w("dates and exclusions match by *column*, ordering by sort direction, grouping by")
    w("grouped column, and `COUNT(id)` is treated as equivalent to `COUNT(*)`.")
    w("")
    w(f"- **Recall** = (required items correctly extracted) / (required items).  A missing")
    w(f"  requirement is *not* counted against precision.")
    w(f"- **Precision** = (correctly extracted) / (all extracted).  An unsupported extra")
    w(f"  is *not* counted against recall.")
    w(f"- **Macro** = mean of per-case values.  **Micro** = pooled items across all cases.")
    w("")
    w("Layer A intentionally scores only ring + date facets: choosing the metric column")
    w("(business-rule driven) and entity/table selection are the model's job and are")
    w("scored in Layer B. So a low Layer-A recall on a `multi`/`aggregation` question")
    w("means *the deterministic layer does not resolve that filter type*, not that the")
    w("final answer is wrong.")
    w("")
    w("## 2. Headline results (Layer B — full pipeline)")
    w("")
    w(f"**{S['total']} questions, all executed live** (model + warehouse).")
    w("")
    w("| Metric | Macro | Micro |")
    w("|---|---|---|")
    w(f"| **Recall** | {pct(B['macro_recall'])} | {pct(B['micro_recall'])} |")
    w(f"| **Precision** | {pct(B['macro_precision'])} | {pct(B['micro_precision'])} |")
    w("")
    w(f"- **Mis-routed to the futures warehouse: {len(mis)} / {S['total']}** "
      f"({pct(len(mis) / S['total'])}) — the dominant error (see §6).")
    w(f"- Correction rounds used: {sum(corrs)} total across {len(corrs)} cases "
      f"(max {max(corrs) if corrs else 0}) — the model is essentially single-shot.")
    w("")
    w("### Diagnostic layer (Layer A — deterministic extraction)")
    w("")
    w("| Metric | Macro | Micro |")
    w("|---|---|---|")
    w(f"| Recall | {pct(A['macro_recall'])} | {pct(A['micro_recall'])} |")
    w(f"| Precision | {pct(A['macro_precision'])} | {pct(A['micro_precision'])} |")
    w("")
    w("Layer A resolves rings and absolute Persian dates almost perfectly; it cannot")
    w("resolve customer type, currency, offer/contract kind, or status — those are the")
    w("misses below, by design.")
    w("")
    w("## 3. Results by question category")
    w("")
    w("| Category | n | Recall B | Precision B | Recall A | Precision A |")
    w("|---|---:|---:|---:|---:|---:|")
    order = ["simple", "multi", "analytical", "ambiguous", "date", "aggregation", "negative"]
    for c in order:
        v = S["by_category"].get(c)
        if not v:
            continue
        w(f"| {c} | {v['n']} | {pct(v['B_R'])} | {pct(v['B_P'])} "
          f"| {pct(v['A_R'])} | {pct(v['A_P'])} |")
    w("")
    w("**Reading:** the system is strongest on well-specified questions (negative "
    f"{pct(S['by_category']['negative']['B_R'])}, date {pct(S['by_category']['date']['B_R'])}, "
    f"aggregation {pct(S['by_category']['aggregation']['B_R'])}) and weakest on the **ambiguous** "
    f"category (recall {pct(S['by_category']['ambiguous']['B_R'])}, precision "
    f"{pct(S['by_category']['ambiguous']['B_P'])}) — where under-specified questions invite "
    "unsupported assumptions and the futures mis-route concentrates.")
    w("")
    w("## 4. Best and worst test cases (Layer B)")
    w("")
    w("### Best")
    w("")
    w("| ID | Category | Recall | Precision | Question |")
    w("|---|---|---:|---:|---|")
    for r in best:
        w(f"| {r['id']} | {r['category']} | {pct(r['B_recall_raw'])} | {pct(r['B_precision_raw'])} "
          f"| {cell(r['question'])} |")
    w("")
    w("### Worst")
    w("")
    w("| ID | Category | Recall | Precision | Missing requirements |")
    w("|---|---|---:|---:|---|")
    for r in worst:
        w(f"| {r['id']} | {r['category']} | {pct(r['B_recall_raw'])} | {pct(r['B_precision_raw'])} "
          f"| {cell(r['B_missing'])} |")
    w("")
    w("## 5. Frequently missed requirements (Layer B)")
    w("")
    w("How often each required item failed to be extracted, across all 100 cases:")
    w("")
    w("| # | Missing requirement |")
    w("|---:|---|")
    for k, v in miss_b.most_common(20):
        w(f"| {v} | {cell(k)} |")
    w("")
    w("## 6. Frequently added unsupported items (Layer B)")
    w("")
    w("Items the system extracted that the question did not ask for:")
    w("")
    w("| # | Extra item |")
    w("|---:|---|")
    for k, v in extra_b.most_common(20):
        w(f"| {v} | {cell(k)} |")
    w("")
    w("## 7. Dominant error: cross-warehouse mis-routing")
    w("")
    w(f"Of {S['total']} cases, **{len(mis)} mis-route to the futures/CSD warehouse** instead of")
    w("the auction warehouse — `Future_Fact.Trade` (with `Future_Dim.Contract`) or the CSD")
    w("`vTrades` views. Distribution by category:")
    w("")
    for c, n in mis_by_cat.most_common():
        w(f"- **{c}**: {n}")
    w("")
    w("Trigger is generic, unanchored phrasing — `معامله` (trade), `قیمت` (price), `حجم`")
    w("(volume), `آمار` (statistics) — which the model maps to the futures `Trade` fact. The")
    w("auction facts are only chosen when the question is *anchored* to an auction word")
    w("(`قرارداد`/contract, `عرضه`/offer, `سفارش`/order, `مشتری`/customer).")
    w("")
    w("| ID | Question (abridged) | Recall |")
    w("|---|---|---:|")
    for r in mis:
        w(f"| {r['id']} | {cell(r['question'][:70])} | {pct(r['B_recall_raw'])} |")
    w("")
    w("Consequence: even a syntactically valid query answers the **wrong domain**")
    w("(futures trade volume, not auction contract value), so the answer is substantively")
    w("wrong despite clean SQL. This is the single largest driver of the sub-0.6 recall on")
    w("the ambiguous category.")
    w("")
    w("## 8. Common interpretation errors (summary)")
    w("")
    w("1. **Cross-warehouse mis-route** (14 cases) — the biggest issue; generic trade/price/")
    w("   volume words resolve to `Future_Fact.Trade` rather than the auction facts.")
    w("2. **Symbol grouping lost** — top-symbol questions miss the `Symbol` entity and the")
    w("   `GROUP BY symbol` (4 misses each); the model groups by contract/customer instead.")
    w("3. **Offer-kind / clearing-kind / currency / contract-kind filters dropped** — the")
    w("   multi-condition filters the deterministic layer can't resolve and the model often")
    w("   omits or guesses (e.g. `OfferKind=export`, `Currency=دلار`, `ClearingKind=نقدی`).")
    w("4. **Ring sometimes dropped on a single filter** — 5 cases lost the ring filter,")
    w("   usually when the mis-route also replaced it with a futures commodity-group filter.")
    w("5. **`COUNT` vs row-list** — a few questions asking for a count got a row listing")
    w("   (or vice-versa); the metric type was off even when the table was right.")
    w("6. **Day-of-week** — `PersianDayOfWeek` extraction is fragile (شنبه=1 was read as 6 in")
    w("   one case), so weekday-anchored questions under-performed.")
    w("7. **Strong spots** — exact Persian dates, seasons, top-N by value, and exclusion")
    w("   filters (not-cancelled, not-premium) were handled well; negatives averaged 96.7% recall.")
    w("")
    w("## 9. Recommendations")
    w("")
    w("**For the NLQ pipeline (highest impact first):**")
    w("")
    w("1. **Fix cross-warehouse routing.** This deployment's default source is `Auction_DM`,")
    w("   yet unanchored questions flip to `Future_DM`. Options: (a) bias the source selector")
    w("   toward the default/auction source when the question names no futures-specific term;")
    w("   (b) teach the retrieval layer that `معامله`/`قیمت`/`حجم` are auction-ambiguous and")
    w("   should default to the auction facts or trigger a clarification rather than silently")
    w("   choosing futures; (c) add the auction facts' Persian aliases (معامله→Contract/Trade)")
    w("   so the auction source wins the keyword tie. This alone would recover ~14 cases.")
    w("2. **Strengthen symbol handling.** `Symbol` grouping is repeatedly dropped on top-N")
    w("   commodity questions; ensure the `Symbol` dimension is retrieved and the GROUP BY is")
    w("   preserved when a question references `نماد`/commodity.")
    w("3. **Surface the unresolvable filters as clarifications.** Customer type, currency,")
    w("   offer/clearing kind are not in the deterministic tier and are frequently dropped.")
    w("   Declaring them as assumptions/clarifications (as the ranking flow already does) would")
    w("   convert silent misses into visible, correctable choices.")
    w("4. **Robust weekday extraction.** Persian-day-of-week mapping has off-by-one cases; the")
    w("   `extract_day_of_week` patterns should be re-validated against the 1380–1408 date table.")
    w("")
    w("**For this benchmark:**")
    w("")
    w("- The futures mis-route is a *source-selection* defect, partially outside pure")
    w("  interpretation; it is counted here because a wrong-domain answer is an incorrect")
    w("  interpretation. A future revision could report it as a separate axis so the two")
    w("  failure modes (right warehouse, wrong filter vs. wrong warehouse) stay distinguishable.")
    w("- Layer A is a stable, model-free regression signal: it can be run in CI without the")
    w("  LLM or warehouse to catch retrieval/alias regressions cheaply.")
    w("")
    w("## 10. Detailed per-case results (Layer B — headline)")
    w("")
    w("| Test ID | Question | Expected requirements | Extracted | Missing | Extra | Recall | Precision |")
    w("|---|---|---|---|---|---|---:|---:|")
    for r in rows:
        w(f"| {r['id']} | {cell(r['question'][:64])} | {cell(r['expected_ref'])} "
          f"| {cell(r['B_extracted'])} | {cell(r['B_missing'])} | {cell(r['B_extra'])} "
          f"| {r['B_recall']} | {r['B_precision']} |")
    w("")
    w("> `expected_ref` is the ground truth (abbreviated labels); `Extracted`/`Missing`/`Extra`")
    w("> are the Layer B requirement items. The full SQL, Layer A items, corrections and")
    w("> status for every case are in `recall_precision_results.csv` and `recall_precision_run.json`.")
    w("")

    OUT.write_text("\n".join(L), encoding="utf-8")
    print(f"Wrote {OUT}")
    print(f"  cases={S['total']}  B macro R={pct(B['macro_recall'])} P={pct(B['macro_precision'])}  "
          f"misroutes={len(mis)}")


if __name__ == "__main__":
    main()
