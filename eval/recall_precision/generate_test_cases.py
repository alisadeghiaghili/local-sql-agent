def item(type_, ref, match=None, optional=False, allow=None, label=None):
    d = {"type": type_, "ref": ref}
    if match:
        d["match"] = match
    if optional:
        d["optional"] = True
    if allow:
        d["allow"] = list(allow)
    if label:
        d["label"] = label
    return d


def ent(ref, label=None, allow=None, optional=False):
    return item("entity", ref, match="entity", optional=optional, allow=allow, label=label)


def metric(ref, label=None, optional=False, allow=None):
    return item("metric", ref, optional=optional, allow=allow, label=label)


def ring(name, optional=False, label=None):
    return item("filter", f"auction_dim.ring.name={name}", match="value",
                optional=optional, label=label or f"ring={name}")


def year(y, optional=False, label=None):
    return item("date", f"general_dim.date.persianyear={y}", match="value",
                optional=optional, label=label or f"year={y}")


def month(m, optional=False, label=None):
    return item("date", f"general_dim.date.persianmonthname={m}", match="value",
                optional=optional, label=label or f"month={m}")


def season(s, optional=False, label=None):
    return item("date", f"general_dim.date.persianseasonname={s}", match="value",
                optional=optional, label=label or f"season={s}")


def dow(n, optional=False, label=None):
    return item("date", f"general_dim.date.persiandayofweek={n}", match="value",
                optional=optional, label=label or f"dow={n}")


def rel_date(column, match="column", label=None, optional=False):
    return item("date", column, match=match, optional=optional, label=label)


def datecol(column, value, label=None, optional=False):
    return item("date", f"{column}={value}", match="value", optional=optional, label=label)


def group(col, label=None, optional=False, allow=None):
    return item("grouping", col, match="group", optional=optional, allow=allow, label=label)


def order(direction, label=None, optional=False, allow=None):
    return item("ordering", f"col {direction}", match="direction",
                optional=optional, allow=allow, label=label)


def top(n, label=None):
    if n is None:
        return item("top", "*any*", label=label, optional=True)
    return item("top", str(n), label=label)


def excl(col, label=None, optional=False):
    return item("exclusion", col, match="column", optional=optional, label=label)


def custom(type_, ref, match=None, label=None, optional=False, allow=None):
    return item(type_, ref, match=match, optional=optional, allow=allow, label=label)


