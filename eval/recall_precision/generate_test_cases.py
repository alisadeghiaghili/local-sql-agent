def build():
    cases = []
    counts = {}
    for (cid, cat, question, items, note) in CASES:
        counts[cat] = counts.get(cat, 0) + 1
        cases.append({
            "id": cid,
            "category": cat,
            "category_fa": CAT[cat],
            "question": question,
            "expected": {"items": items},
            "note": note,
        })
    return {"meta": {
        "name": "NLQ recall/precision benchmark",
        "version": "1.0",
        "total": len(cases),
        "by_category": counts,
        "generated": str(Path(__file__).resolve()),
        "scoring": "requirement-level recall/precision; Layer B (full pipeline) "
                   "is the headline, Layer A (deterministic retrieval) is a "
                   "diagnostic. See evaluate_recall_precision.py.",
    }, "cases": cases}


def main():
    data = build()
    with open(OUT, "w", encoding="utf-8") as fh:
        json.dump(data, fh, ensure_ascii=False, indent=2)
    print(f"Wrote {data['meta']['total']} cases -> {OUT}")
    print("By category:", data["meta"]["by_category"])
    ids = [c["id"] for c in data["cases"]]
    assert len(ids) == len(set(ids)), "duplicate ids"
    assert data["meta"]["total"] == 100, f"expected 100 cases, got {data['meta']['total']}"


if __name__ == "__main__":
    main()
