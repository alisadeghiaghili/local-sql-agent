        assert second.asked == ["sales.Customer", "ref.Bank"]
        after = validate_schema_yaml_text(described(project))
        assert after.tables["sales.Trade"].columns["ID"] == "Identifier chosen by a person"  # carried as it is now
        assert after.tables["sales.Customer"].columns["Name"] == "Name of the customer"
        assert after.tables["ref.Bank"].description == "One row per bank."
        assert described(project).count("# AUTO-GENERATED by draft_descriptions.py") == 1

