        assert main([], generate=model) == EXIT_FAILED_TABLES

        after = validate_schema_yaml_text(described(project))
        assert after.tables["sales.Trade"].description == "One row per trade made with a customer."
        assert after.tables["ref.Bank"].description == "ref.Bank (view)"
        assert "interrupted" in capsys.readouterr().out


