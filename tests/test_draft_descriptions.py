    def test_an_existing_output_is_not_replaced_without_resume_or_force(self, project, capsys):
        (project / DESCRIBED).write_text("# reviewed by hand\n", encoding="utf-8")
        model = FakeModel()

        assert main([], generate=model) == EXIT_ERROR

        assert model.prompts == []
        assert (project / DESCRIBED).read_text(encoding="utf-8") == "# reviewed by hand\n"
        assert "--resume" in capsys.readouterr().err
        assert main(["--force"], generate=model) == EXIT_OK
        assert "AUTO-GENERATED by draft_descriptions.py" in described(project)

