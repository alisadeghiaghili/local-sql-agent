class FakeModel:
    """Stands for ``WizardLLM.generate``: answers by the table named in the prompt."""

    def __init__(self, answers=None):
        self.answers = dict(ANSWERS if answers is None else answers)
        self.prompts: list[str] = []
        self.tokens: list[int] = []

    def __call__(self, prompt: str):
        self.prompts.append(prompt)
        self.tokens.append(cfg.settings.llm_num_predict)
        key = re.search(r"^Table: (.*)$", prompt, re.MULTILINE).group(1)
        answer = self.answers[key]
        if isinstance(answer, Exception):
            raise answer
        return answer

    @property
    def asked(self) -> list[str]:
        return [re.search(r"^Table: (.*)$", p, re.MULTILINE).group(1) for p in self.prompts]


@pytest.fixture()
def project(tmp_path):
    (tmp_path / "schema.yaml").write_text(SCHEMA, encoding="utf-8", newline="\n")
    with cfg.override_settings(project_config_dir=str(tmp_path)):
        yield tmp_path


def described(project: Path) -> str:
    return (project / DESCRIBED).read_text(encoding="utf-8")


def edits(before: str, after: str) -> list[tuple[list[str], list[str]]]:
    """``(old lines, new lines)`` for every place the texts differ, the header line of *after* taken off."""
    old, new = before.split("\n"), after.split("\n")
    assert new[0].startswith("# AUTO-GENERATED by draft_descriptions.py")
    new = new[1:]
    matcher = difflib.SequenceMatcher(a=old, b=new, autojunk=False)
    return [(old[i1:i2], new[j1:j2]) for tag, i1, i2, j1, j2 in matcher.get_opcodes() if tag != "equal"]


class TestWhatIsDrafted:
    def test_only_draft_descriptions_are_targets(self):
        targets = {t.key: t for t in describe.find_targets(SCHEMA)}

        assert set(targets) == {"sales.Trade", "sales.Customer", "ref.Bank", "ref.Note"}
        assert targets["sales.Trade"] == describe.TableTarget(
            "sales.Trade", True, ("ID", "Status", "Amount", "Phone")
        )
        # A curated table description is not a target even when a column of it is.
        assert targets["sales.Customer"] == describe.TableTarget("sales.Customer", False, ("Name",))
        # "ref.Bank (view)" is only the name; the empty description of ref.Note counts too.
        assert targets["ref.Bank"].describe_table and targets["ref.Bank"].columns == ("ID",)
        assert targets["ref.Note"].describe_table
        assert "ref.Region" not in targets

    def test_the_inspectors_placeholder_is_a_target(self):
        text = "tables:\n  T:\n    description: 's.T \u2014 auto-detected fact table (~10 rows)'\n"
        assert describe.find_targets(text) == [describe.TableTarget("T", True, ())]

    def test_it_uses_the_preflights_own_detectors(self):
        # What this script drafts is what the preflight objects to, nothing else.
        view = doctor.read_schema_text(SCHEMA)
        named, _ = doctor.name_only_descriptions(view)
        typed, _ = doctor.type_only_column_notes(view)
        targets = describe.find_targets(SCHEMA)
        assert named == 2  # sales.Trade, ref.Bank
        assert typed == sum(len(t.columns) for t in targets) - 1  # all but Amount, which is empty


class TestTheDraftFile:
    def test_it_drafts_what_is_missing_and_keeps_everything_else_byte_for_byte(self, project, capsys):
        model = FakeModel()

        code = main([], generate=model)

        assert code == EXIT_OK
        text = described(project)
        changes = edits(SCHEMA, text)
        # Exactly the draft descriptions changed, each one line for one line; the one
        # table without a description line (ref.Note) gets a new line.
        assert [[line.strip() for line in old] for old, _ in changes] == [
            ['description: "sales.Trade"  # TO BE FILLED (added by sync_schema.py)'],
            ['ID: "bigint column"  # TO BE FILLED (added by sync_schema.py)'],
            ['Status: "nvarchar(20) column"', 'Amount: ""', 'Phone: "varchar(20) column"'],
            ['Name: "varchar(100) column"'],
            ['description: "ref.Bank (view)"'],
            ['ID: "int column"'],
            [],
            ['ID: "int column"'],
        ]
        assert [len(new) for _, new in changes] == [1, 1, 3, 1, 1, 1, 1, 1]
        assert all(line.rstrip().endswith("# REVIEW") for _, new in changes for line in new)
        # schema.yaml itself is never touched.
        assert (project / "schema.yaml").read_text(encoding="utf-8") == SCHEMA
        out = capsys.readouterr().out
        assert "written:" in out and "failed tables: 0" in out

