class TestParseAnswer:
    FACTS = describe_prompt.TableFacts(
        "sales.Trade", "Trade", "sales",
        columns=(
            describe_prompt.ColumnFact("ID", "int", "Primary key"),
            describe_prompt.ColumnFact("Status", wanted=True),
            describe_prompt.ColumnFact("Amount", wanted=True),
        ),
    )

    def test_names_are_matched_ignoring_case_and_unknown_ones_are_ignored(self):
        got = describe_prompt.parse_answer(
            {"table": "Trades.", "columns": {"status": "State", "ID": "no", "Nope": "no", "Amount": "Amount"}}, self.FACTS
        )

        assert got.description == "Trades." and dict(got.columns) == {"Status": "State"}
        assert got.ignored == 3

    def test_a_list_of_name_and_description_items_is_accepted(self):
        got = describe_prompt.parse_answer(
            {"description": "Trades.", "columns": [{"name": "Amount", "description": "Sum"}, {"name": 3}, "x"]}, self.FACTS
        )

        assert got.description == "Trades." and dict(got.columns) == {"Amount": "Sum"}

    def test_text_is_one_line_and_cut(self):
        got = describe_prompt.parse_answer(
            {"table": '  "A\n table   of trades"  ', "columns": {"Status": "x" * 500}}, self.FACTS
        )

        assert got.description == "A table of trades"
        assert len(got.columns["Status"]) == describe_prompt.COLUMN_TEXT_LIMIT

    def test_the_columns_come_back_in_the_tables_order(self):
        got = describe_prompt.parse_answer({"table": "T.", "columns": {"Amount": "a", "Status": "s"}}, self.FACTS)
        assert list(got.columns) == ["Status", "Amount"]

    def test_nothing_usable_is_an_error(self):
        for answer in (None, [], "x", {}, {"columns": {"Nope": "x"}}, {"table": "Trade", "columns": {"Amount": "bigint column"}}):
            with pytest.raises(ValueError):
                describe_prompt.parse_answer(answer, self.FACTS)

    def test_a_table_description_is_not_looked_for_when_it_was_not_asked_for(self):
        facts = describe_prompt.TableFacts("T", "T", describe_table=False, columns=(describe_prompt.ColumnFact("A", wanted=True),))

        got = describe_prompt.parse_answer({"table": "Ignored.", "columns": {"A": "Kept"}}, facts)

        assert got.description == "" and dict(got.columns) == {"A": "Kept"}


