"""A clarification answered in live mode brings the analyst to the new answer (#219).

Pressing a clarification option (or editing an assumption) in live mode sends
``PATCH .../assumptions``; the server re-asks the question and answers with a
new turn under its own ``turn_id`` (``TurnEngine.ask`` appends it to the
session). ``web/js/main.js``'s ``rerenderTurn`` finds no card for that id and
appends one at the foot of the transcript, but the page stayed where it was,
so the answer appeared out of sight. It now scrolls to the new card's result,
as a streamed answer does once it settles. A turn that already has a card is
still replaced in place, without a scroll.

Extracts the REAL ``rerenderTurn`` from ``web/js/main.js`` with the same
brace scanner as ``test_web_ui_onclarify_live_mode.py`` and drives it under
Node against spies (see ``run_rerender_turn_scroll.mjs``).

Requires ``node`` on PATH. Skipped (not failed) when unavailable.
"""

from __future__ import annotations
from tests.web_ui import NODE_TIMEOUT_SECONDS

import shutil
import subprocess
import tempfile
from pathlib import Path

import pytest

from tests.web_ui.test_web_ui_onclarify_live_mode import _extract_function

_REPO_ROOT = Path(__file__).resolve().parent.parent.parent
_MAIN_JS = _REPO_ROOT / "web" / "js" / "main.js"
_HARNESS = Path(__file__).resolve().parent / "run_rerender_turn_scroll.mjs"
_NODE = shutil.which("node")

_RERENDER_TURN_SIGNATURE = "function rerenderTurn(turn) {"

_HARNESS_MODULE_TEMPLATE = """\
// AUTO-GENERATED by tests/web_ui/test_web_ui_rerender_turn_scroll.py -- do
// not edit by hand. Embeds the REAL, unmodified `rerenderTurn` extracted
// verbatim from web/js/main.js, wired to spies.

export const calls = {{ appended: [], scrolled: [], cleared: 0 }};
export const dom = {{ existing: new Map(), withResult: true }};

export function resetCalls() {{
  calls.appended.length = 0;
  calls.scrolled.length = 0;
  calls.cleared = 0;
}}

const document = {{ getElementById: (id) => dom.existing.get(id) || null }};

function turnCtx() {{ return {{}}; }}

// The card's result is also recorded on its element, so the runner can
// check the scroll target from what was appended.
function createTurnCard(turn) {{
  const result = dom.withResult ? {{ resultOf: turn.turn_id }} : null;
  const el = {{ turnId: turn.turn_id, result }};
  return {{ el, result }};
}}

const transcript = {{
  appendChild: (el) => {{ calls.appended.push(el); return el; }},
}};
function $(id) {{
  if (id !== "transcript") throw new Error(`unexpected $(${{id}})`);
  return transcript;
}}

function clearTranscriptEmptyState() {{ calls.cleared += 1; }}

function scrollSettledResultAboveComposer(el) {{ calls.scrolled.push(el); }}

// ---- extracted verbatim from web/js/main.js ----------------------------
{rerender_turn_src}
// ---- end extracted source -----------------------------------------------

export {{ rerenderTurn }};
"""


def _write_harness_module(tmp_path: Path) -> Path:
    src = _MAIN_JS.read_text(encoding="utf-8")
    rerender_src = _extract_function(src, _RERENDER_TURN_SIGNATURE, "rerenderTurn")
    module_src = _HARNESS_MODULE_TEMPLATE.format(rerender_turn_src=rerender_src)
    out = tmp_path / "rerender_turn_harness.mjs"
    out.write_text(module_src, encoding="utf-8")
    return out


@pytest.mark.skipif(_NODE is None, reason="node is not on PATH -- cannot execute web/js/*.js under test")
def test_a_new_turn_is_scrolled_to_and_an_existing_one_is_replaced_in_place() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        module_path = _write_harness_module(Path(tmp))
        result = subprocess.run(
            [_NODE, str(_HARNESS), str(module_path)],
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=NODE_TIMEOUT_SECONDS,
        )

    assert result.returncode == 0, (
        f"rerenderTurn scroll check failed.\n"
        f"--- stdout ---\n{result.stdout}\n--- stderr ---\n{result.stderr}"
    )
    assert "ALL_SCENARIOS_PASSED" in result.stdout, (
        f"harness did not report completion (partial run?).\n"
        f"--- stdout ---\n{result.stdout}\n--- stderr ---\n{result.stderr}"
    )
