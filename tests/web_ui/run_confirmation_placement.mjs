// tests/web_ui/run_confirmation_placement.mjs
//
// Node-side half of tests/web_ui/test_web_ui_confirmation_placement.py.
//
// Drives the REAL turn.js (and its real render/ dependency chain, staged
// like run_request_access.mjs) together with the real confirmation.js, wired
// the way web/js/main.js wires it (ctx.renderConfirmation), to prove where
// the «پاسخ درست است» toggle is:
//
// * ON the answer: inside the result card, in a .result-footer under the
//   table, NOT inside the collapsed <details> drawer -- so it is there
//   without opening anything;
// * exactly one toggle per card (the drawer holds the wrong-answer flag only);
// * shown only for a successful answer: absent for an out-of-scope turn, an
//   error, a guard rejection, and when the page supplies no control;
// * the two ratings still undo each other in the UI: flagging resets a
//   pressed toggle, and confirming after a flag reopens the flag control.
//
// Usage: node run_confirmation_placement.mjs <copied-turn.mjs> <copied-confirmation.mjs>
//
// Exits 0 and prints "ALL_SCENARIOS_PASSED" iff every scenario passed.

