/** The page's wiring, as web/js/main.js's ctx.renderConfirmation does it. */
function makeCtx(log, { withConfirmation = true } = {}) {
  const confirmed = new Set();
  const ctx = {
    onFlag: async (turnId, category, note) => { log.push(["flag", turnId, category]); },
  };
  if (withConfirmation) {
    ctx.renderConfirmation = (turn, { onReplacedFlag }) => {
      if (!canConfirm(turn)) return null;
      return renderConfirmationControl(turn, {
        confirmed: confirmed.has(turn.turn_id),
        onConfirm: async () => { log.push(["confirm", turn.turn_id]); confirmed.add(turn.turn_id); return { removed_flags: ctx.removedFlags ?? 0 }; },
        onWithdraw: async () => { log.push(["withdraw", turn.turn_id]); confirmed.delete(turn.turn_id); },
        onConfirmed: (result) => {
          const replaced = Boolean(result && result.removed_flags > 0);
          if (replaced) onReplacedFlag();
          return replaced;
        },
      });
    };
  }
  return ctx;
}

const all = (root, selector) => root.querySelectorAll(selector);
const drawerOf = (card) => all(card.el, "details")[0];
async function press(el) { for (const h of el._listeners.click || []) await h({ preventDefault() {} }); }

// ---------------------------------------------------------------------
// Scenario 1: on the answer, outside the drawer, exactly once.
// ---------------------------------------------------------------------
{
  const card = createTurnCard(successTurn(), makeCtx([]));
  const toggles = all(card.el, "button.confirm-toggle");
  assert.equal(toggles.length, 1, "exactly one confirmation toggle per card (no duplicate)");
  const toggle = toggles[0];
  const drawer = drawerOf(card);
  assert.ok(drawer, "the details drawer exists");
  assert.equal(drawer.querySelector("button.confirm-toggle"), null, "NOT inside the collapsed drawer");
  assert.equal(drawer.open ?? false, false, "the drawer is closed: the toggle is there without opening it");
  assert.ok(toggle.closest(".result-footer"), "in the answer's footer row");
  assert.ok(toggle.closest(".result-footer").closest(".card"), "inside the result card");
  assert.equal(card.result.querySelector("button.confirm-toggle"), toggle, "the card returned as `result` holds it");
  assert.equal(toggle.getAttribute("aria-pressed"), "false");
  assert.equal(toggle.textContent, "پاسخ درست است");
  assert.equal(toggle.type ?? "button", "button");
  // The footer comes after the result block in the card, i.e. under the table/chart.
  const resultCard = card.result;
  const kids = resultCard.children.map((c) => c.className);
  assert.ok(kids.indexOf("result-block") < kids.indexOf("result-footer"), `footer after the result: ${kids}`);
  console.log("[ok] one toggle, in the result card's footer, outside the closed drawer");
}

// ---------------------------------------------------------------------
// Scenario 2: the drawer keeps the wrong-answer flag, and only that.
// ---------------------------------------------------------------------
{
  const card = createTurnCard(successTurn(), makeCtx([]));
  const drawer = drawerOf(card);
  assert.ok(drawer.querySelector("button.feedback-toggle"), "the flag control stays in the drawer");
  console.log("[ok] the flag control stays in the drawer");
}

// ---------------------------------------------------------------------
// Scenario 3: absent on every turn that is not a successful answer.
// ---------------------------------------------------------------------
{
  for (const [name, turn] of [
    ["out-of-scope", outOfScopeTurn()],
    ["guard-rejected", guardRejectedTurn()],
    ["execution error", failedExecutionTurn()],
  ]) {
    const card = createTurnCard(turn, makeCtx([]));
    assert.equal(all(card.el, "button.confirm-toggle").length, 0, `no toggle on a ${name} turn`);
    assert.equal(all(card.el, ".result-footer").length, 0, `no footer on a ${name} turn`);
  }
  const bare = createTurnCard(successTurn(), makeCtx([], { withConfirmation: false }));
  assert.equal(all(bare.el, "button.confirm-toggle").length, 0, "nothing is rendered when the page supplies no control");
  console.log("[ok] absent on out-of-scope, guard-rejected and failed turns, and when unwired");
}

// ---------------------------------------------------------------------
// Scenario 4: pressing it works from the answer, with the drawer closed.
// ---------------------------------------------------------------------
{
  const log = [];
  const card = createTurnCard(successTurn(), makeCtx(log));
  const toggle = all(card.el, "button.confirm-toggle")[0];
  await press(toggle);
  assert.deepEqual(log, [["confirm", "t_ok"]]);
  assert.equal(toggle.getAttribute("aria-pressed"), "true");
  assert.ok(toggle.textContent.includes("✓") && toggle.textContent.includes("پاسخ درست است"));
  await press(toggle);
  assert.deepEqual(log.at(-1), ["withdraw", "t_ok"]);
  assert.equal(toggle.getAttribute("aria-pressed"), "false");
  console.log("[ok] confirming and withdrawing from the answer, drawer closed");
}

// ---------------------------------------------------------------------
// Scenario 5: the two ratings still undo each other in the UI.
// ---------------------------------------------------------------------
{
  const log = [];
  const ctx = makeCtx(log);
  const card = createTurnCard(successTurn(), ctx);
  const toggle = all(card.el, "button.confirm-toggle")[0];
  const submit = drawerOf(card).querySelector("button.feedback-submit");
  const flagToggle = drawerOf(card).querySelector("button.feedback-toggle");

  await press(toggle);
  assert.equal(toggle.getAttribute("aria-pressed"), "true");
  await press(submit);
  assert.equal(log.at(-1)[0], "flag");
  assert.equal(toggle.getAttribute("aria-pressed"), "false", "flagging resets the toggle on the answer");
  assert.equal(submit.disabled, true, "precondition: the flag was submitted");

  ctx.removedFlags = 1;
  await press(toggle);
  assert.equal(toggle.getAttribute("aria-pressed"), "true");
  assert.equal(submit.disabled, false, "confirming after a flag reopens the flag control");
  assert.equal(flagToggle.textContent, "این عدد درست نیست؟");
  console.log("[ok] flag and confirmation reset each other across the answer and the drawer");
}

console.log("ALL_SCENARIOS_PASSED");
